import type {
  Env,
  Gallery,
  InlineKeyboardMarkup,
  PanelEntry,
  SeriesEntry,
  SeriesFile,
} from "./types";
import { parseIssue, slugify } from "./caption";
import { formatIssue, mutateJsonFile, readGalleryJson, readJsonFile } from "./github";

/**
 * A rateable thing. `series` is the series the target belongs to — the target
 * itself when `type` is "series" — so `/rate_series` can walk up from an issue
 * and a write echo can quote both aggregates without a second resolve.
 */
export interface RatingTarget {
  type: "issue" | "series";
  id: string;
  label: string;
  series: { id: string; label: string };
}

export interface Aggregate {
  avg: number | null;
  count: number;
}

/** One person's mark on one target. `uid` is the identity key — see `userKey`. */
export interface RatingRow {
  uid: string;
  user: string;
  score: number | null;
  review: string | null;
  createdAt: string;
  updatedAt: string;
}

export interface TargetRatings {
  label: string;
  avg: number | null;
  count: number;
  ratings: RatingRow[];
}

export interface RatingsIndex {
  generatedAt: string;
  targets: Record<string, TargetRatings>;
}

export const RATINGS_PATH = "public/data/ratings.json";

const MAX_REVIEW_CHARS = 1000;
const CACHE_ORIGIN = "https://cache.comic-snaps.internal";
const SOURCE_CACHE_SECONDS = 60;

// ---------------------------------------------------------------------------
// Cached source reads
// ---------------------------------------------------------------------------

/**
 * Cache a derived value in the edge cache for a minute. Resolving a panel
 * number or a series name costs a GitHub read; the tap path (§1.1) never needs
 * one, but the `/rate` path would pay it on every command without this.
 */
async function cachedJson<T>(key: string, load: () => Promise<T>): Promise<T> {
  const req = new Request(`${CACHE_ORIGIN}/${key}`);
  const cache = caches.default;

  const hit = await cache.match(req);
  if (hit) return (await hit.json()) as T;

  const data = await load();
  await cache.put(
    req,
    new Response(JSON.stringify(data), {
      headers: {
        "Content-Type": "application/json",
        "Cache-Control": `max-age=${SOURCE_CACHE_SECONDS}`,
      },
    })
  );
  return data;
}

async function loadGallery(env: Env): Promise<Gallery> {
  return cachedJson("gallery", async () => (await readGalleryJson(env)).gallery);
}

async function loadSeries(env: Env): Promise<SeriesEntry[]> {
  return cachedJson("series", async () => {
    const { data } = await readJsonFile<SeriesFile>(env, "public/data/series.json");
    return data?.series ?? [];
  });
}

// ---------------------------------------------------------------------------
// Target ids
// ---------------------------------------------------------------------------

/**
 * `{series-slug}-{issue-slug}` — the same transform a panel id is built from
 * (`index.ts`), so two panels from one issue collapse onto one target.
 * Deliberately not keyed off `issues.json`: that file only carries
 * Metron-sourced issues, and ratings have to stand alone (§2.1).
 */
export function issueTargetId(slug: string, issue: number | string): string {
  return `${slug}-${slugify(String(issue))}`;
}

export function issueLabel(title: string, issue: number | string): string {
  return `${title} ${formatIssue(issue)}`;
}

/** The rating target for a gallery panel — the issue it came from, not the panel. */
export function targetForPanel(panel: PanelEntry, forceSeries: boolean): RatingTarget {
  const series = { id: panel.slug, label: panel.title };
  if (forceSeries) {
    return { type: "series", id: series.id, label: series.label, series };
  }
  return {
    type: "issue",
    id: issueTargetId(panel.slug, panel.issue),
    label: issueLabel(panel.title, panel.issue),
    series,
  };
}

// ---------------------------------------------------------------------------
// Reference grammar (§1.6)
// ---------------------------------------------------------------------------

interface SeriesInfo {
  id: string;
  name: string;
  aliases: string[];
}

function normalize(s: string): string {
  return s.trim().toLowerCase();
}

/**
 * Everything that can be named as a series: the metadata records plus every
 * slug the gallery actually uses. The gallery half matters because
 * `series.json` is generated by a separate metadata pass that may not have run
 * for a freshly posted series.
 */
async function seriesIndex(env: Env): Promise<SeriesInfo[]> {
  const [gallery, series] = await Promise.all([loadGallery(env), loadSeries(env)]);

  const byId = new Map<string, SeriesInfo>();
  for (const p of gallery.panels) {
    if (!p.slug) continue;
    if (!byId.has(p.slug)) byId.set(p.slug, { id: p.slug, name: p.title, aliases: [] });
  }
  for (const s of series) {
    const existing = byId.get(s.id);
    const aliases = (s.aliases ?? []).filter((a): a is string => !!a);
    if (existing) {
      existing.name = s.name || existing.name;
      existing.aliases = aliases;
    } else {
      byId.set(s.id, { id: s.id, name: s.name, aliases });
    }
  }
  return Array.from(byId.values());
}

function matchSeries(list: SeriesInfo[], ref: string): SeriesInfo | undefined {
  const r = normalize(ref);
  if (!r) return undefined;
  return (
    list.find((s) => normalize(s.id) === r) ??
    list.find((s) => normalize(s.name) === r) ??
    list.find((s) => s.aliases.some((a) => normalize(a) === r))
  );
}

/** Near misses for a reference that matched nothing, so recovery can be a tap. */
function seriesCandidates(list: SeriesInfo[], ref: string, limit = 6): SeriesInfo[] {
  const r = normalize(ref);
  if (!r) return [];
  const scored = list
    .map((s) => {
      const name = normalize(s.name);
      const id = normalize(s.id);
      if (name.startsWith(r) || id.startsWith(r)) return { s, rank: 0 };
      if (name.includes(r) || id.includes(r)) return { s, rank: 1 };
      if (r.includes(name) && name.length > 2) return { s, rank: 2 };
      return null;
    })
    .filter((x): x is { s: SeriesInfo; rank: number } => x !== null)
    .sort((a, b) => a.rank - b.rank || a.s.name.localeCompare(b.s.name));
  return scored.slice(0, limit).map((x) => x.s);
}

function seriesTarget(s: SeriesInfo): RatingTarget {
  return {
    type: "series",
    id: s.id,
    label: s.name,
    series: { id: s.id, label: s.name },
  };
}

function issueTarget(s: SeriesInfo, issueRef: string): RatingTarget {
  const issue = parseIssue(issueRef);
  return {
    type: "issue",
    id: issueTargetId(s.id, issue),
    label: issueLabel(s.name, issue),
    series: { id: s.id, label: s.name },
  };
}

export interface ResolveOpts {
  /** `/rate_series` — every reference lands on the series. */
  forceSeries?: boolean;
  /** Target of the message this command replied to, if any. */
  replyTarget?: RatingTarget | null;
}

export type ResolveResult =
  | { ok: true; target: RatingTarget }
  | { ok: false; message: string; candidates: RatingTarget[] };

function fail(message: string, candidates: SeriesInfo[] = []): ResolveResult {
  return { ok: false, message, candidates: candidates.map(seriesTarget) };
}

/** Narrow a resolved target to its series when the command forces it. */
function applyForce(target: RatingTarget, forceSeries: boolean): RatingTarget {
  if (!forceSeries || target.type === "series") return target;
  return {
    type: "series",
    id: target.series.id,
    label: target.series.label,
    series: target.series,
  };
}

/**
 * The one reference resolver every rating command shares (§1.6). Steps are
 * tried in the documented order — in particular the whole string is tried as a
 * series name *before* a trailing number is split off, so `2000 AD` and `100%`
 * resolve as series rather than as a series plus an issue.
 */
export async function resolveTarget(
  env: Env,
  ref: string,
  opts: ResolveOpts = {}
): Promise<ResolveResult> {
  const force = opts.forceSeries ?? false;
  const trimmed = ref.trim();

  // 1. Explicit prefix — the escape hatch for anything the heuristics misread.
  const prefixed = trimmed.match(/^(panel|series|issue):\s*(.+)$/i);
  if (prefixed) {
    const kind = prefixed[1].toLowerCase();
    const rest = prefixed[2].trim();

    if (kind === "panel") {
      if (!/^\d+$/.test(rest)) return fail(`"${rest}" isn't a panel number.`);
      const panel = await findPanel(env, parseInt(rest, 10));
      if (!panel) return fail(`No panel found with ID ${rest}.`);
      return { ok: true, target: targetForPanel(panel, force) };
    }

    const list = await seriesIndex(env);
    if (kind === "series") {
      const s = matchSeries(list, rest);
      if (!s) return fail(`No series found matching "${rest}".`, seriesCandidates(list, rest));
      return { ok: true, target: seriesTarget(s) };
    }

    // issue:saga-4 — a raw target id. Label it from a panel when one exists.
    const gallery = await loadGallery(env);
    const panel = gallery.panels.find(
      (p) => issueTargetId(p.slug, p.issue) === normalize(rest)
    );
    if (panel) return { ok: true, target: targetForPanel(panel, force) };
    const owner = list.find((s) => normalize(rest).startsWith(`${normalize(s.id)}-`));
    const series = owner
      ? { id: owner.id, label: owner.name }
      : { id: normalize(rest), label: rest };
    if (force) {
      return { ok: true, target: { type: "series", id: series.id, label: series.label, series } };
    }
    return { ok: true, target: { type: "issue", id: normalize(rest), label: rest, series } };
  }

  // 2. Empty reference in a reply — the replied-to message's target.
  if (!trimmed) {
    if (opts.replyTarget) {
      return { ok: true, target: applyForce(opts.replyTarget, force) };
    }
    return fail("Which one? Reply to a panel, or name it: /rate Saga #4 8");
  }

  // 3. Bare digits — a panel `seq`. Takes precedence over a series *named*
  //    with digits; `series:100` disambiguates. Falls through when no panel
  //    carries that number, so `/rate 100 9` still reaches the series 100%.
  if (/^\d+$/.test(trimmed)) {
    const panel = await findPanel(env, parseInt(trimmed, 10));
    if (panel) return { ok: true, target: targetForPanel(panel, force) };
  }

  const list = await seriesIndex(env);

  // 4. `#` marker — everything after it is the issue, verbatim, so
  //    `Hellboy #Annual 2` works. A failing head is a real error, not a reason
  //    to reinterpret the string.
  const hashIdx = trimmed.indexOf("#");
  if (hashIdx > 0) {
    const head = trimmed.slice(0, hashIdx).trim();
    const issueRef = trimmed.slice(hashIdx + 1).trim();
    if (issueRef) {
      const s = matchSeries(list, head);
      if (!s) return fail(`No series found matching "${head}".`, seriesCandidates(list, head));
      return { ok: true, target: applyForce(issueTarget(s, issueRef), force) };
    }
  }

  // 5. The whole string as a series name.
  const whole = matchSeries(list, trimmed);
  if (whole) return { ok: true, target: seriesTarget(whole) };

  // 6. Trailing token as the issue.
  const split = trimmed.match(/^(.*\S)\s+(\S+)$/);
  if (split) {
    const s = matchSeries(list, split[1]);
    if (s) return { ok: true, target: applyForce(issueTarget(s, split[2]), force) };
  }

  return fail(`No series or panel found matching "${trimmed}".`, seriesCandidates(list, trimmed));
}

async function findPanel(env: Env, seq: number): Promise<PanelEntry | null> {
  const gallery = await loadGallery(env);
  return gallery.panels.find((p) => p.seq === seq) ?? null;
}

