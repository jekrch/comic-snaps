function emptyIndex(): RatingsIndex {
  return { generatedAt: new Date().toISOString(), targets: {} };
}

export function targetKey(type: "issue" | "series", id: string): string {
  return `${type}:${id}`;
}

/**
 * A stable, opaque identity for a rater. The file is published, so the raw
 * Telegram id can't go in it — but re-rating has to find the same row, and a
 * first name is neither stable nor unique. Salted, so the short digest can't be
 * walked back to an id by brute force.
 */
export async function userKey(env: Env, telegramId: number): Promise<string> {
  const salt = env.RATINGS_SALT ?? env.WEBHOOK_SECRET ?? "comic-snaps";
  const digest = await crypto.subtle.digest(
    "SHA-256",
    new TextEncoder().encode(`${salt}:${telegramId}`)
  );
  return Array.from(new Uint8Array(digest).slice(0, 6))
    .map((b) => b.toString(16).padStart(2, "0"))
    .join("");
}

function round1(n: number): number {
  return Math.round(n * 10) / 10;
}

/**
 * Recompute a target's average from its rows. Score and review are independent,
 * so a row carrying only a review contributes nothing to the mean — and the
 * count is published next to the average rather than hidden behind a prior,
 * because at this group size the count *is* the caveat (§8).
 */
function reaggregate(entry: TargetRatings): void {
  const scores = entry.ratings.map((r) => r.score).filter((v): v is number => v !== null);
  entry.count = scores.length;
  entry.avg = scores.length ? round1(scores.reduce((a, b) => a + b, 0) / scores.length) : null;
  entry.ratings.sort(
    (a, b) => (b.score ?? -1) - (a.score ?? -1) || b.updatedAt.localeCompare(a.updatedAt)
  );
}

export interface UpsertResult {
  previous: { score: number | null; review: string | null } | null;
  current: { score: number | null; review: string | null };
  removed: boolean;
  target: Aggregate;
  series: Aggregate;
  label: string;
}

export async function readRatings(env: Env): Promise<RatingsIndex> {
  const { data } = await readJsonFile<RatingsIndex>(env, RATINGS_PATH);
  return data ?? emptyIndex();
}

/**
 * Add or change one person's rating, then commit the file. A score alone leaves
 * an existing review untouched and a review alone leaves the score untouched
 * (§1.2) — that's the only merge rule, and it's why score and review share one
 * row rather than being two entities. A row left with neither is dropped.
 */
export async function upsertRating(
  env: Env,
  target: RatingTarget,
  user: { id: number; name: string },
  score: number | null,
  review: string | null
): Promise<UpsertResult> {
  const uid = await userKey(env, user.id);
  const now = new Date().toISOString();
  const key = targetKey(target.type, target.id);
  const seriesKey = targetKey("series", target.series.id);

  return mutateJsonFile<RatingsIndex, UpsertResult>(env, RATINGS_PATH, emptyIndex, (index) => {
    index.generatedAt = now;
    const entry = (index.targets[key] ??= {
      label: target.label,
      avg: null,
      count: 0,
      ratings: [],
    });
    entry.label = target.label;

    const existing = entry.ratings.find((r) => r.uid === uid) ?? null;
    const previous = existing ? { score: existing.score, review: existing.review } : null;

    const row: RatingRow = existing ?? {
      uid,
      user: user.name,
      score: null,
      review: null,
      createdAt: now,
      updatedAt: now,
    };
    if (!existing) entry.ratings.push(row);

    row.user = user.name;
    if (score !== null) row.score = score;
    if (review !== null) row.review = review;
    row.updatedAt = now;

    let removed = false;
    if (row.score === null && row.review === null) {
      entry.ratings = entry.ratings.filter((r) => r.uid !== uid);
      removed = true;
    }

    reaggregate(entry);
    const label = entry.label;
    const aggregate: Aggregate = { avg: entry.avg, count: entry.count };
    if (entry.ratings.length === 0) delete index.targets[key];

    const seriesEntry = index.targets[seriesKey];
    return {
      result: {
        previous,
        current: { score: row.score, review: row.review },
        removed,
        target: aggregate,
        series: seriesEntry
          ? { avg: seriesEntry.avg, count: seriesEntry.count }
          : { avg: null, count: 0 },
        label,
      },
      message: `Rate ${target.label}: ${user.name} ${score ?? "review"}`,
    };
  });
}

export function aggregateFrom(
  index: RatingsIndex,
  type: "issue" | "series",
  id: string
): Aggregate {
  const entry = index.targets[targetKey(type, id)];
  return entry ? { avg: entry.avg, count: entry.count } : { avg: null, count: 0 };
}

export function ratingsFrom(
  index: RatingsIndex,
  type: "issue" | "series",
  id: string
): RatingRow[] {
  return index.targets[targetKey(type, id)]?.ratings ?? [];
}

